/** Generate the MCP catalogue from the explicit backend OAuth contract.
 * Swagger supplies descriptions only; it never expands the authorized surface.
 * bun run gen:endpoints [swagger.json | --offline]
 */
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(root, "src/endpoints.generated.ts");
const contract = JSON.parse(readFileSync(join(root, "docs/oauth-business-routes.json"), "utf8"));
const shape = (method, path) => method + " " + path.replace(/\{[^}]+\}/g, "{}");
const descriptions = new Map();
const arg = process.argv[2];
if (arg === "--offline") {
  const source = readFileSync(outFile, "utf8");
  const match = source.match(/export const MAGILEADS_ENDPOINTS[^=]*= ([\s\S]+);\s*$/);
  if (!match) throw new Error("Cannot read the committed catalogue.");
  for (const row of JSON.parse(match[1])) descriptions.set(shape(row.method, row.path), row);
} else {
  let swagger;
  if (arg) swagger = JSON.parse(readFileSync(arg, "utf8"));
  else {
    const response = await fetch("https://api.magileads.net/swagger.json", { signal: AbortSignal.timeout(30_000) });
    if (!response.ok) throw new Error("Swagger HTTP " + response.status);
    swagger = await response.json();
  }
  for (const [path, methods] of Object.entries(swagger.paths ?? {})) {
    for (const [method, spec] of Object.entries(methods)) {
      if (!["get", "post", "put"].includes(method) || !spec || typeof spec !== "object") continue;
      descriptions.set(shape(method.toUpperCase(), path), { tag: spec.tags?.[0], summary: spec.summary });
    }
  }
}
const seen = new Set();
const list = contract.map((row) => {
  const key = shape(row.method, row.path);
  if (!["GET", "POST", "PUT"].includes(row.method) || !["mcp:read", "mcp:write"].includes(row.scope) ||
      !row.path.startsWith("/") || seen.has(key)) throw new Error("Invalid or duplicate contract operation: " + key);
  seen.add(key);
  const info = descriptions.get(key);
  return { method: row.method, path: row.path, tag: info?.tag || row.tag,
    summary: (info?.summary || row.summary).slice(0, 140), scope: row.scope, write: row.scope === "mcp:write" };
});
list.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
const header = [
  "// AUTO-GENERATED by scripts/generate-endpoints.mjs — do not edit by hand.",
  "// Authorization source: docs/oauth-business-routes.json (backend contract).",
  "// Swagger supplies descriptions only. DELETE, PATCH and undocumented routes are excluded.",
  "// " + list.length + " operations (" + list.filter((e) => !e.write).length + " read, " + list.filter((e) => e.write).length + " write).",
  "",
  'import type { Scope } from "./oauth/scopes.js";',
  'export type EndpointDef = { method: "GET" | "POST" | "PUT"; path: string; tag: string; summary: string; scope: Scope; write: boolean };',
  "",
  "export const MAGILEADS_ENDPOINTS: EndpointDef[] = [",
  list.map((row) => "  " + JSON.stringify(row)).join(",\n"),
  "];", "",
].join("\n");
writeFileSync(outFile, header, "utf8");
console.error("Wrote " + list.length + " explicitly authorized operations to " + outFile);
